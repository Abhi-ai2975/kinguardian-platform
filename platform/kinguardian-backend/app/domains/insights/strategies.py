# 4. Weight Trend Strategy
# ==========================================

class WeightTrendStrategy(BaseTrendStrategy):
    metric_name = "weight"

    async def analyze(
        self,
        subject_id: uuid.UUID,
        family_id: uuid.UUID,
        observations: List[Dict[str, Any]],
        timeframe_days: int = 7
    ) -> Optional[TrendAnalysisResult]:
        """
        Detects rapid weight changes (e.g. > 2.5 kg gain over 5 days indicating fluid retention).
        """
        now = datetime.now()
        start = now - timedelta(days=timeframe_days)

        weight_obs = [
            o for o in observations
            if o.get("code") in ("weight", "body_weight", "29463-7")
        ]
        if len(weight_obs) < 2:
            return None

        # Sort by timestamp
        weight_obs.sort(key=lambda x: x.get("date", str(now)))
        first_weight = float(weight_obs[0].get("value", 0))
        last_weight = float(weight_obs[-1].get("value", 0))
        diff = round(last_weight - first_weight, 1)

        # Rapid weight gain >= 2.5 kg
        if diff >= 2.5:
            return TrendAnalysisResult(
                metric_name=self.metric_name,
                detected=True,
                title="Rapid Weight Increase Detected",
                summary=f"Weight increased by +{diff} kg over the last {timeframe_days} days ({first_weight} kg → {last_weight} kg).",
                observation="Rapid weight gain over a short period may be an early sign of fluid retention in cardiac/renal monitoring.",
                recommendation="Assess for pedal edema or shortness of breath and notify primary care physician.",
                severity="warning",
                type="guardian_moment",
                confidence=0.93,
                baseline_comparison=f"Increase of +{diff} kg exceeds normal daily variation (< 1.0 kg).",
                actionability="Recommend clinical review for fluid status.",
                timeframe_start=start,
                timeframe_end=now,
                source_records=[{"source_type": "fhir_observation", "source_id": str(subject_id), "metadata": {"weight_delta_kg": diff}}]
            )

        return None


