# 2. Sleep Trend Strategy
# ==========================================

class SleepTrendStrategy(BaseTrendStrategy):
    metric_name = "sleep"

    async def analyze(
        self,
        subject_id: uuid.UUID,
        family_id: uuid.UUID,
        observations: List[Dict[str, Any]],
        timeframe_days: int = 7
    ) -> Optional[TrendAnalysisResult]:
        """
        Detects sleep duration anomalies and nighttime restlessness.
        """
        now = datetime.now()
        start = now - timedelta(days=timeframe_days)

        sleep_obs = [
            o for o in observations
            if o.get("code") in ("sleep_duration", "sleep", "total_sleep_hours")
        ]
        if len(sleep_obs) < 3:
            return None

        sleep_hours = [float(o.get("value", 0)) for o in sleep_obs]
        avg_sleep = sum(sleep_hours) / len(sleep_hours)

        if avg_sleep < 5.5:
            return TrendAnalysisResult(
                metric_name=self.metric_name,
                detected=True,
                title="Persistent Short Sleep Duration",
                summary=f"Nightly sleep averaged only {round(avg_sleep, 1)} hours over the past {timeframe_days} days.",
                observation="Sleep duration has consistently stayed below the 6-hour minimum healthy threshold.",
                recommendation="Review nighttime routine and assess potential nighttime restlessness or discomfort.",
                severity="warning",
                type="guardian_moment",
                confidence=0.91,
                baseline_comparison="Reduced from standard 7.2h baseline.",
                actionability="Suggest reviewing sleep environment and caffeine/medication timing.",
                timeframe_start=start,
                timeframe_end=now,
                source_records=[{"source_type": "wearable_sleep", "source_id": str(subject_id), "metadata": {"avg_sleep_hours": avg_sleep}}]
            )

        return None


